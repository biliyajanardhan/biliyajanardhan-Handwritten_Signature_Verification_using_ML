class KaggleSiameseDataset(Dataset):
    def __init__(self, root_dir, transform=None):
        self.root_dir = root_dir
        self.transform = transform
        self.pairs = []
        self.labels = []

        # --- DYNAMIC LOOKUP LAYER TO PREVENT PATH ERRORS ---
        possible_paths = [
            os.path.join(root_dir, "cedar", "CEDAR"),
            os.path.join(root_dir, "cedar", "cedar"),
            os.path.join(root_dir, "CEDAR"),
            os.path.join(root_dir, "cedar")
        ]

        cedar_path = None
        for path_option in possible_paths:
            if os.path.exists(path_option) and any(fname.endswith('.png') for fname in os.listdir(path_option)):
                cedar_path = path_option
                break

        if cedar_path is None:
            # Fallback assignment to root if no subfolders match criteria
            cedar_path = root_dir

        print(f"[Data Loader] Target verification directory resolved to: {cedar_path}")

        positive_count = 0
        negative_count = 0

        # Person IDs range from 1 to 55 in the CEDAR dataset
        for person_id in range(1, 56):
            genuine_pattern = os.path.join(cedar_path, f"original_{person_id}_*.png")
            forged_pattern = os.path.join(cedar_path, f"forgeries_{person_id}_*.png")

            genuine_imgs = sorted(glob.glob(genuine_pattern))
            forged_imgs = sorted(glob.glob(forged_pattern))

            if len(genuine_imgs) == 0:
                continue

            # Create Positive Pairs (Genuine + Genuine) -> Label = 0
            for i in range(len(genuine_imgs)):
                for j in range(i + 1, min(i + 5, len(genuine_imgs))):
                    self.pairs.append((genuine_imgs[i], genuine_imgs[j]))
                    self.labels.append(0.0)
                    positive_count += 1

            # Create Negative Pairs (Genuine + Forged) -> Label = 1
            for i in range(min(len(genuine_imgs), 15)):
                for j in range(min(len(forged_imgs), 15)):
                    self.pairs.append((genuine_imgs[i], forged_imgs[j]))
                    self.labels.append(1.0)
                    negative_count += 1

        print(f"✅ Data Extraction Complete!")
        print(f"   ├── Total Positive Pairs (Genuine-Genuine): {positive_count}")
        print(f"   ├── Total Negative Pairs (Genuine-Forged): {negative_count}")
        print(f"   └── Total Dataset Signature Pairs: {len(self.pairs)}")

        if len(self.pairs) == 0:
            raise RuntimeError(f"🚨 Critical Failure: 0 images matched standard naming pattern inside {cedar_path}. Verify folder directory contents.")

    def __len__(self):
        return len(self.pairs)

    def __getitem__(self, idx):
        img1_path, img2_path = self.pairs[idx]
        img1 = Image.open(img1_path).convert("RGB")
        img2 = Image.open(img2_path).convert("RGB")
        label = torch.tensor(self.labels[idx], dtype=torch.float32)

        if self.transform:
            img1 = self.transform(img1)
            img2 = self.transform(img2)

        return img1, img2, label

