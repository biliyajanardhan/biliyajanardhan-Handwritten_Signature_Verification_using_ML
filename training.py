class SiameseResNet(nn.Module):
    def __init__(self, embedding_dim=128):
        super(SiameseResNet, self).__init__()
        # Loads a pre-trained ResNet-18 base network model
        self.backbone = models.resnet18(weights=models.ResNet18_Weights.DEFAULT)
        num_features = self.backbone.fc.in_features
        self.backbone.fc = nn.Identity()  # Strip final classification layer

        # Custom Fully Connected head for vector embedding
        self.fc_head = nn.Sequential(
            nn.Linear(num_features, 512),
            nn.ReLU(inplace=True),
            nn.Dropout(p=0.3),
            nn.Linear(512, embedding_dim)
        )

    def forward_once(self, x):
        output = self.backbone(x)
        output = self.fc_head(output)
        return output

    def forward(self, input1, input2):
        output1 = self.forward_once(input1)
        output2 = self.forward_once(input2)
        return output1, output2

model = SiameseResNet(embedding_dim=config["Embedding Dimension"]).to(device)

