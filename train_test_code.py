def evaluate_model(
    model,
    data_loader,
    criterion,
    device,
    threshold=1.0
):

    model.eval()


    total_loss = 0.0
    correct = 0
    total = 0


    with torch.no_grad():

        for img1, img2, label in data_loader:

            img1 = img1.to(
                device,
                non_blocking=True
            )

            img2 = img2.to(
                device,
                non_blocking=True
            )

            label = label.to(
                device,
                non_blocking=True
            )


            output1, output2 = model(
                img1,
                img2
            )


            loss = criterion(
                output1,
                output2,
                label
            )


            total_loss += (
                loss.item()
                * img1.size(0)
            )


            distance = nn.functional.pairwise_distance(
                output1,
                output2
            )


            # Smaller distance = same signature
            predicted = (
                distance > threshold
            ).float()


            correct += (
                predicted == label
            ).sum().item()


            total += label.size(0)


    avg_loss = (
        total_loss / total
        if total > 0
        else 0
    )


    accuracy = (
        correct / total
        if total > 0
        else 0
    )


    return avg_loss, accuracy


