def create_pairs(
    signer_list,
    max_positive_per_signer=100,
    max_negative_per_signer=100
):

    pairs = []
    labels = []


    for signer_key in signer_list:

        genuine = signer_images[
            signer_key
        ]["genuine"]

        forged = signer_images[
            signer_key
        ]["forged"]


        # ----------------------------------------------------
        # POSITIVE PAIRS
        # Genuine + Genuine
        # Label = 0
        # ----------------------------------------------------

        positive_pairs = []


        for i in range(
            len(genuine)
        ):

            for j in range(
                i + 1,
                len(genuine)
            ):

                positive_pairs.append(
                    (
                        genuine[i],
                        genuine[j]
                    )
                )


        random.shuffle(
            positive_pairs
        )


        positive_pairs = positive_pairs[
            :max_positive_per_signer
        ]


        for pair in positive_pairs:

            pairs.append(pair)

            labels.append(0.0)


        # ----------------------------------------------------
        # NEGATIVE PAIRS
        # Genuine + Forged
        # Label = 1
        # ----------------------------------------------------

        negative_pairs = []


        for genuine_path in genuine:

            for forged_path in forged:

                negative_pairs.append(
                    (
                        genuine_path,
                        forged_path
                    )
                )


        random.shuffle(
            negative_pairs
        )


        negative_pairs = negative_pairs[
            :max_negative_per_signer
        ]


        for pair in negative_pairs:

            pairs.append(pair)

            labels.append(1.0)


    return pairs, labels


