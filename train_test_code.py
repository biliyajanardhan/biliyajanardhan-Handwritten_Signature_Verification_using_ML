class SignaturePairDataset(Dataset):

    def __init__(
        self,
        pairs,
        labels,
        transform=None
    ):

        self.pairs = pairs
        self.labels = labels
        self.transform = transform


    def __len__(self):

        return len(
            self.pairs
        )


    def __getitem__(self, index):

        image1_path, image2_path = (
            self.pairs[index]
        )


        image1 = Image.open(
            image1_path
        ).convert("RGB")


        image2 = Image.open(
            image2_path
        ).convert("RGB")


        if self.transform:

            image1 = self.transform(
                image1
            )

            image2 = self.transform(
                image2
            )


        label = torch.tensor(
            self.labels[index],
            dtype=torch.float32
        )


        return (
            image1,
            image2,
            label
        )


