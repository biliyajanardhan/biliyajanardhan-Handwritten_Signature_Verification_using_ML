def classify_signature(path):

    """
    Determine whether an image is genuine or forged.

    We inspect the filename and parent directory names.
    """

    text = path.lower()

    # Forged indicators
    forged_keywords = [
        "forg",
        "forged",
        "forgery",
        "forge",
        "fake"
    ]

    # Genuine indicators
    genuine_keywords = [
        "genuine",
        "original",
        "real"
    ]


    for keyword in forged_keywords:

        if keyword in text:

            return "forged"


    for keyword in genuine_keywords:

        if keyword in text:

            return "genuine"


    # --------------------------------------------------------
    # BHSig260 common filename patterns
    #
    # If the dataset uses a final G/F marker,
    # detect it here.
    # --------------------------------------------------------

    filename = os.path.basename(
        path
    ).lower()


    # Remove extension
    filename_without_ext = os.path.splitext(
        filename
    )[0]


    # Tokenize
    tokens = re.split(
        r"[_\-\s]+",
        filename_without_ext
    )


    for token in tokens:

        if token in [
            "g",
            "genuine"
        ]:

            return "genuine"


        if token in [
            "f",
            "forged",
            "forgery"
        ]:

            return "forged"


    return "unknown"


